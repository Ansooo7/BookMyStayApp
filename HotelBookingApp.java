/**
 * HotelBookingApp
 * 
 * A simple entry-point demonstration for the Hotel Booking application.
 * Shows how execution begins in Java and produces console output.
 * 
 * @author Student
 * @version 1.0.0
 */
public class HotelBookingApp {

    /**
     * The main method is the entry point of every Java application.
     * The JVM looks for this exact signature to begin execution.
     *
     * @param args Command-line arguments passed to the program
     */
    public static void main(String[] args) {
        // Console output using String literals
        System.out.println("Welcome to Hotel Booking Application!");
        System.out.println("Application Name: HotelBookingApp");
        System.out.println("Version: 1.0.0");

        // Program terminates after printing messages
    }
}
